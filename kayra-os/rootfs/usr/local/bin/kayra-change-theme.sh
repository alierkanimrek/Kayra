#!/usr/bin/env bash
#
# kayra-change-theme.sh - Apply the GTK palette to SwayNC, Sway and Fuzzel.
#
# The palette JSON is produced by kayra-theme-probe.gjs. Waybar reads the colors
# directly from the GTK theme. SwayNC is a GTK4 application, but the Yaru GTK4
# theme's gresource is not available to it in this environment, so its colors
# are written directly. The script writes:
#
#   ~/.config/swaync/theme.css         SwayNC color definitions
#   ~/.config/sway/theme-colors.conf   client.* window colors
#   ~/.config/fuzzel/colors.ini        [colors] section
#
# The files are written atomically and only when their content changes. When
# something changed, the running Sway session is updated with swaymsg and the
# GTK applications are reloaded (Waybar with SIGUSR2, SwayNC with
# swaync-client -rs).
#
# Usage: kayra-change-theme.sh '<json>'
# Exit: 0 on success (including "nothing changed"), 1 on error.
#
# Used libraries: klog.sh
# Used commands: jq, mktemp, cmp, mv, chmod, mkdir, dirname, swaymsg, pkill,
#                swaync-client
#

set -euo pipefail
export LC_ALL=C.UTF-8

source /usr/local/lib/kayra/klog.sh

CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
SWAYNC_COLORS="$CONFIG_HOME/swaync/theme.css"
SWAY_COLORS="$CONFIG_HOME/sway/theme-colors.conf"
FUZZEL_COLORS="$CONFIG_HOME/fuzzel/colors.ini"

json=${1:-}
if [ -z "$json" ]; then
    log ERROR "missing palette JSON argument"
    exit 1
fi

if ! jq -e '
        type == "object"
        and ([.bg, .surface, .fg, .selected_bg, .selected_fg, .warning, .error]
             | all(.[]; type == "string" and test("^#[0-9a-fA-F]{6}$")))
    ' >/dev/null 2>&1 <<<"$json"; then
    log ERROR "invalid palette JSON"
    exit 1
fi

read -r bg surface fg selected_bg selected_fg warning error < <(
    jq -r '[.bg, .surface, .fg, .selected_bg, .selected_fg, .warning, .error] | @tsv' <<<"$json"
)

# Writes $2 to $1 atomically.
# Returns 0 when the file changed, 1 when it was already up to date, 2 on error.
write_atomic() {
    local target="$1" content="$2" tmp
    mkdir -p "$(dirname -- "$target")" || return 2
    tmp=$(mktemp "$target.XXXXXX") || return 2
    printf '%s' "$content" >"$tmp" || { rm -f "$tmp"; return 2; }
    chmod 0644 "$tmp" || { rm -f "$tmp"; return 2; }
    if [ -f "$target" ] && cmp -s "$tmp" "$target"; then
        rm -f "$tmp"
        return 1
    fi
    mv -f "$tmp" "$target" || { rm -f "$tmp"; return 2; }
    return 0
}

printf -v swaync_content '%s\n' \
    '/*' \
    ' * Kayra OS - SwayNotificationCenter color theme' \
    ' * Generated by kayra-change-theme.sh - do not edit.' \
    ' * The font is configured in style.css.' \
    ' */' \
    "@define-color color-bg         $bg;" \
    "@define-color color-surface    $surface;" \
    "@define-color color-fg         $fg;" \
    "@define-color color-fg-hover   $selected_bg;" \
    "@define-color color-warning    $warning;" \
    "@define-color color-error      $error;"

printf -v sway_content '%s\n' \
    '# Generated by kayra-change-theme.sh - do not edit.' \
    "client.focused           $selected_bg $bg $fg $selected_bg $selected_bg" \
    "client.focused_inactive  $surface $bg $fg $surface $surface" \
    "client.focused_tab_title $surface $bg $fg" \
    "client.unfocused         $surface $bg $fg $surface $surface" \
    "client.urgent            $error $bg $fg $error $error"

bg_hex=${bg#\#}
fg_hex=${fg#\#}
selected_bg_hex=${selected_bg#\#}
selected_fg_hex=${selected_fg#\#}

printf -v fuzzel_content '%s\n' \
    '# Generated by kayra-change-theme.sh - do not edit.' \
    '[colors]' \
    "background=${bg_hex}ff" \
    "text=${fg_hex}ff" \
    "match=${selected_fg_hex}ff" \
    "selection=${selected_bg_hex}ff" \
    "selection-text=${selected_fg_hex}ff" \
    "selection-match=${fg_hex}ff" \
    "border=${fg_hex}ff"

changed=0

if write_atomic "$SWAYNC_COLORS" "$swaync_content"; then
    changed=1
else
    rc=$?
    if [ "$rc" -eq 2 ]; then
        log ERROR "cannot write $SWAYNC_COLORS"
        exit 1
    fi
fi

if write_atomic "$SWAY_COLORS" "$sway_content"; then
    changed=1
else
    rc=$?
    if [ "$rc" -eq 2 ]; then
        log ERROR "cannot write $SWAY_COLORS"
        exit 1
    fi
fi

if write_atomic "$FUZZEL_COLORS" "$fuzzel_content"; then
    changed=1
else
    rc=$?
    if [ "$rc" -eq 2 ]; then
        log ERROR "cannot write $FUZZEL_COLORS"
        exit 1
    fi
fi

if [ "$changed" -eq 0 ]; then
    log DEBUG "theme colors are already up to date"
    exit 0
fi

# Apply the window border colors to the running Sway session. The generated
# file is used on the next session start.
if command -v swaymsg >/dev/null 2>&1 && [ -n "${SWAYSOCK:-}" ]; then
    swaymsg "client.focused $selected_bg $bg $fg $selected_bg $selected_bg" >/dev/null 2>&1 || true
    swaymsg "client.focused_inactive $surface $bg $fg $surface $surface" >/dev/null 2>&1 || true
    swaymsg "client.focused_tab_title $surface $bg $fg" >/dev/null 2>&1 || true
    swaymsg "client.unfocused $surface $bg $fg $surface $surface" >/dev/null 2>&1 || true
    swaymsg "client.urgent $error $bg $fg $error $error" >/dev/null 2>&1 || true
fi

# GTK applications read the colors directly from the GTK theme; reload their
# CSS so the new palette is picked up.
pkill -USR2 -x waybar 2>/dev/null || true
if command -v swaync-client >/dev/null 2>&1; then
    swaync-client -rs >/dev/null 2>&1 || true
fi

log INFO "theme colors updated"

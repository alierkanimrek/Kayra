#!/usr/bin/env bash
#
# set-keyboard-layout.sh - Apply a keyboard layout to the sway configuration.
#
# Usage: set-keyboard-layout.sh [--notify] <layout-name>
#   The layout name is the display name of an entry in the keyboard data
#   file, for example "Turkish (Default)" or "Turkish - Turkish (F)".
#   With --notify the result is also shown as a desktop notification.
#
# The xkb_layout and xkb_variant values of the "input type:keyboard" block in
# ~/.config/sway/input-keyboard.conf are replaced, the other content of the
# file is kept. Afterwards the sway configuration is reloaded.
#
# Used commands: awk, sed, mktemp, mv, swaymsg, printf
# Used libraries: i18n.sh, klog.sh, notify.sh

export LC_ALL=C.UTF-8

set -uo pipefail

source "$(dirname "$0")/i18n.sh"
declare -n MSG=i18n_KEYBOARD_SETTINGS

source "$(dirname "$0")/klog.sh"
source "$(dirname "$0")/notify.sh"

DATA_FILE="$HOME/.local/bin/data/keyboard-data"
CONFIG_FILE="$HOME/.config/sway/input-keyboard.conf"

# Material symbol of the keyboard, it is used as the notification icon.
ICON_KEYBOARD=$(printf '%b' '\U000E30C')

NOTIFY_ICON="$ICON_KEYBOARD"

# The notification is only sent when the script runs on its own.
USE_NOTIFY=0
if [[ "${1:-}" == "--notify" ]]; then
    USE_NOTIFY=1
    shift
fi

SELECTION="${1:-}"

if [[ -z "$SELECTION" ]]; then
    log ERROR "No keyboard layout was given"
    if [[ $USE_NOTIFY -eq 1 ]]; then
        notify_error "${MSG[NOTIFY_TITLE]}" "${MSG[ERROR_NO_SELECTION]}"
    fi
    echo "Error: no keyboard layout was given" >&2
    exit 1
fi

# The data file is generated by generate-keyboard-data.sh.
if [[ ! -f "$DATA_FILE" ]]; then
    log ERROR "The keyboard data file is missing: $DATA_FILE"
    if [[ $USE_NOTIFY -eq 1 ]]; then
        notify_error "${MSG[NOTIFY_TITLE]}" "${MSG[ERROR_DATA_NOT_FOUND]}"
    fi
    echo "Error: keyboard data file not found: $DATA_FILE" >&2
    exit 1
fi

# Look up the layout and the variant of the selected entry.
ENTRY=$(awk -F'|' -v want="$SELECTION" '
    {
        name = $1
        sub(/^[[:space:]]+/, "", name)
        sub(/[[:space:]]+$/, "", name)
        if (name == want) {
            print $2 "|" $3
            exit
        }
    }
' "$DATA_FILE")

if [[ -z "$ENTRY" ]]; then
    log ERROR "The selection was not found in the keyboard database: $SELECTION"
    if [[ $USE_NOTIFY -eq 1 ]]; then
        notify_error "${MSG[NOTIFY_TITLE]}" "${MSG[ERROR_SELECTION_NOT_FOUND]}"
    fi
    echo "Error: selection not found in the keyboard database: $SELECTION" >&2
    exit 1
fi

LAYOUT="${ENTRY%%|*}"
VARIANT="${ENTRY#*|}"

if [[ -z "$LAYOUT" ]]; then
    log ERROR "The entry of the keyboard database has no layout: $SELECTION"
    if [[ $USE_NOTIFY -eq 1 ]]; then
        notify_error "${MSG[NOTIFY_TITLE]}" "${MSG[ERROR_SELECTION_NOT_FOUND]}"
    fi
    echo "Error: the keyboard database entry has no layout: $SELECTION" >&2
    exit 1
fi

# The config file is created when it does not exist yet.
if [[ ! -f "$CONFIG_FILE" ]]; then
    log ERROR "The keyboard config file is missing: $CONFIG_FILE"
    if [[ $USE_NOTIFY -eq 1 ]]; then
        notify_error "${MSG[NOTIFY_TITLE]}" "${MSG[ERROR_CONFIG_NOT_FOUND]}"
    fi
    echo "Error: keyboard config file not found: $CONFIG_FILE" >&2
    exit 1
fi

# Replace the xkb_layout and the xkb_variant values of the keyboard block.
# The other content of the config file is kept.
TMP_FILE=$(mktemp)

awk -v layout="$LAYOUT" -v variant="$VARIANT" '
    BEGIN { in_block = 0; has_block = 0; has_layout = 0; has_variant = 0 }
    {
        if ($0 ~ /^[[:space:]]*input[[:space:]]+type:keyboard[[:space:]]*\{/) {
            in_block = 1
            has_block = 1
            print
            next
        }
        if (in_block && $0 ~ /^[[:space:]]*\}/) {
            if (!has_layout) print "    xkb_layout \"" layout "\""
            if (variant != "" && !has_variant) print "    xkb_variant \"" variant "\""
            in_block = 0
            print
            next
        }
        if (in_block && $0 ~ /^[[:space:]]*xkb_layout/) {
            print "    xkb_layout \"" layout "\""
            has_layout = 1
            next
        }
        if (in_block && $0 ~ /^[[:space:]]*xkb_variant/) {
            if (variant != "") {
                print "    xkb_variant \"" variant "\""
                has_variant = 1
            }
            next
        }
        print
    }
    END {
        if (!has_block) {
            print ""
            print "input type:keyboard {"
            print "    xkb_layout \"" layout "\""
            if (variant != "") print "    xkb_variant \"" variant "\""
            print "}"
        }
    }
' "$CONFIG_FILE" > "$TMP_FILE"

if ! mv "$TMP_FILE" "$CONFIG_FILE"; then
    rm -f "$TMP_FILE"
    log ERROR "The keyboard config file could not be written: $CONFIG_FILE"
    if [[ $USE_NOTIFY -eq 1 ]]; then
        notify_error "${MSG[NOTIFY_TITLE]}" "${MSG[MSG_FAILED]}"
    fi
    echo "Error: the keyboard config file could not be written: $CONFIG_FILE" >&2
    exit 1
fi

log INFO "Keyboard layout changed to: layout=$LAYOUT variant=$VARIANT"

# Reload the sway configuration.
if ! swaymsg reload >/dev/null 2>&1; then
    log WARN "Failed to reload the sway configuration (swaymsg is not available)"
fi

# Build the result message.
MESSAGE=$(i18n_template "${MSG[MSG_CHANGED]}" "LAYOUT=$SELECTION")
if [[ -n "$VARIANT" ]]; then
    MESSAGE="$MESSAGE - $(i18n_template "${MSG[MSG_VARIANT]}" "VARIANT=$VARIANT")"
fi

echo "$MESSAGE"

if [[ $USE_NOTIFY -eq 1 ]]; then
    notify_ok "${MSG[NOTIFY_TITLE]}" "$MESSAGE"
fi
